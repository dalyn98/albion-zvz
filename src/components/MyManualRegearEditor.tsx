'use client'

// 수동 제출 리기어의 청구액 + 스크린샷 인라인 편집기. 자동 리기어
// (MyRegearBreakdownEditor) 와 달리 슬롯별 단가가 없고 청구자가 직접 적은
// 단일 금액 (claimed_silver) 만 다룬다. pending + 수동인 경우에만 입력 활성화.
// payout 은 승인 시점에 계산되므로 여기선 표시만 하고 직접 갱신하지 않는다.

import { useEffect, useMemo, useRef, useState, useTransition } from 'react'
import { useRouter } from 'next/navigation'
import { useTranslations } from 'next-intl'
import { Save, Loader2, Upload, Clipboard, Trash2, Undo2, ExternalLink } from 'lucide-react'
import { getMyRegearScreenshotUrl, type MyRegearDetail } from '@/app/actions/regear'
import {
  updateMyManualRegearClaim,
  updateMyManualRegearScreenshots,
  updateMyManualRegearVideoProof,
} from '@/app/actions/regear-edit'
import { formatSilver, parseSilverInput } from '@/lib/silver'
import { calcPayoutSilver } from '@/lib/regear-payout'
import { compressImageIfLarge } from '@/lib/image-compress'
import { translateSlotRole } from '@/lib/slot-role-i18n'
import { youtubeVideoProofWatchUrl } from '@/lib/regear-video-proof'
import { useReportDirty } from './UnsavedChangesProvider'

interface Props {
  detail: MyRegearDetail
}

const ACCEPTED_TYPES = ['image/png', 'image/jpeg', 'image/webp']

type SlotKind = 'primary' | 'secondary'

interface ScreenshotSlotState {
  // 서버에 저장된 현재 경로. 아래 pendingRemove === true 면 비워질 예정.
  currentPath: string | null
  // 새로 선택한 파일 — 저장 시 업로드.
  pendingFile: File | null
  // 두 번째 슬롯에서만 의미 있음. true 면 저장 시 삭제.
  pendingRemove: boolean
}

function pathToInitialState(path: string | null): ScreenshotSlotState {
  return { currentPath: path, pendingFile: null, pendingRemove: false }
}

export default function MyManualRegearEditor({ detail }: Props) {
  const router = useRouter()
  const t = useTranslations('regearBreakdown')
  const tMe = useTranslations('me')
  const tReason = useTranslations('regearRejectReason')
  const tRole = useTranslations('slotRole')
  const [claimedSilver, setClaimedSilver] = useState<number>(detail.claimedSilver)
  const [inputValue, setInputValue] = useState<string>(detail.claimedSilver.toString())
  const [error, setError] = useState<string | null>(null)
  const [pending, startTransition] = useTransition()

  // 스크린샷 편집 상태 — 슬롯별로 독립.
  const [primarySlot, setPrimarySlot] = useState<ScreenshotSlotState>(() =>
    pathToInitialState(detail.screenshotPath),
  )
  const [secondarySlot, setSecondarySlot] = useState<ScreenshotSlotState>(() =>
    pathToInitialState(detail.screenshotPath2),
  )
  const [shotError, setShotError] = useState<string | null>(null)
  const [shotPending, startShotTransition] = useTransition()
  const [videoUrl, setVideoUrl] = useState(detail.videoProofUrl ?? '')
  const [savedVideoUrl, setSavedVideoUrl] = useState(detail.videoProofUrl ?? '')
  const [savedVideoTitle, setSavedVideoTitle] = useState(detail.videoProofTitle ?? null)
  const [videoError, setVideoError] = useState<string | null>(null)
  const [videoPending, startVideoTransition] = useTransition()
  const savedVideoWatchUrl = youtubeVideoProofWatchUrl(savedVideoUrl)
  const savedVideoLabel = savedVideoTitle?.trim() || t('videoProofCurrent')

  const editable = detail.status === 'pending' && !detail.autoGenerated
  const expectedPayout = calcPayoutSilver(claimedSilver, detail.payoutRatePercent)

  // 클립보드 붙여넣기로 비어있는 첫 슬롯 자동 채우기. 두 슬롯 모두 채워져 있으면
  // 두 번째 슬롯에 덮어쓴다 (1번째 보존). 비-편집 상태에선 무시.
  useEffect(() => {
    if (!editable) return
    const onPaste = (e: ClipboardEvent) => {
      const items = e.clipboardData?.items
      if (!items) return
      for (const item of items) {
        if (item.kind !== 'file') continue
        if (!ACCEPTED_TYPES.includes(item.type)) continue
        const blob = item.getAsFile()
        if (!blob) continue
        const ext = item.type.split('/')[1]
        const file = new File([blob], `clipboard-${Date.now()}.${ext}`, { type: item.type })
        // 1) primary 가 비었으면 거기에. (현재 path 도 없거나 pendingRemove 인 경우)
        // 2) 그 외엔 secondary.
        const primaryEffectivelyEmpty =
          !primarySlot.pendingFile && !primarySlot.currentPath
        e.preventDefault()
        compressImageIfLarge(file).then((compressed) => {
          if (primaryEffectivelyEmpty) {
            setPrimarySlot((s) => ({ ...s, pendingFile: compressed }))
          } else {
            setSecondarySlot((s) => ({ ...s, pendingFile: compressed, pendingRemove: false }))
          }
        })
        return
      }
    }
    document.addEventListener('paste', onPaste)
    return () => document.removeEventListener('paste', onPaste)
  }, [editable, primarySlot.pendingFile, primarySlot.currentPath])

  const handleSaveClaim = () => {
    const parsed = parseSilverInput(inputValue)
    if (parsed === null || parsed <= 0) {
      setError(t('invalidNumber'))
      return
    }
    if (parsed === claimedSilver) {
      setError(t('manualNoChange'))
      return
    }
    setError(null)
    startTransition(async () => {
      const result = await updateMyManualRegearClaim(detail.id, parsed)
      if (result.error) {
        setError(result.error)
        return
      }
      if (typeof result.claimedSilver === 'number') {
        setClaimedSilver(result.claimedSilver)
        setInputValue(result.claimedSilver.toString())
      }
      router.refresh()
    })
  }

  const hasShotChanges =
    primarySlot.pendingFile !== null ||
    secondarySlot.pendingFile !== null ||
    secondarySlot.pendingRemove
  const videoDirty = videoUrl.trim() !== savedVideoUrl

  // 미저장 변경 가드 — pending + 수동인 경우(=편집 가능)에만 의미가 있다.
  // claimed silver 입력이 원본과 다르거나 스크린샷 변경이 걸려 있으면 dirty.
  const isDirty =
    editable && (inputValue !== detail.claimedSilver.toString() || hasShotChanges || videoDirty)
  useReportDirty(`me-regear:${detail.id}`, isDirty)

  const handleSaveScreenshots = () => {
    if (!hasShotChanges) return
    setShotError(null)
    startShotTransition(async () => {
      const form = new FormData()
      if (primarySlot.pendingFile) form.append('screenshot', primarySlot.pendingFile)
      if (secondarySlot.pendingFile) {
        form.append('screenshot2', secondarySlot.pendingFile)
      } else if (secondarySlot.pendingRemove) {
        form.append('removeSecondary', 'true')
      }
      const result = await updateMyManualRegearScreenshots(detail.id, form)
      if (result.error) {
        setShotError(result.error)
        return
      }
      // 서버가 반환한 새 경로로 상태 동기화. 이후 ScreenshotPreview 가
      // 새 signed URL 을 받아 다시 fetch.
      setPrimarySlot(pathToInitialState(result.primaryPath ?? null))
      setSecondarySlot(pathToInitialState(result.secondaryPath ?? null))
      router.refresh()
    })
  }

  const handleSaveVideoProof = () => {
    if (!videoDirty) return
    setVideoError(null)
    startVideoTransition(async () => {
      const result = await updateMyManualRegearVideoProof(detail.id, videoUrl)
      if (result.error) {
        setVideoError(result.error)
        return
      }
      const next = result.videoProofUrl ?? ''
      setVideoUrl(next)
      setSavedVideoUrl(next)
      setSavedVideoTitle(result.videoProofTitle ?? null)
      router.refresh()
    })
  }

  const statusLabel =
    detail.status === 'pending'
      ? t('statusPending')
      : detail.status === 'approved'
        ? t('statusApproved')
        : t('statusRejected')

  return (
    <div className="space-y-4">
      <header className="bg-gray-900 border border-gray-800 rounded-xl p-4 space-y-2">
        <h1 className="text-lg font-bold text-white">{detail.eventTitle}</h1>
        <div className="flex items-center flex-wrap gap-2 text-xs text-gray-400">
          <span className="bg-gray-800 px-2 py-0.5 rounded">
            {translateSlotRole(detail.roleName, tRole)}
          </span>
          {detail.requestType === 'overcharge' && (
            <span className="rounded bg-orange-500 px-2 py-0.5 font-extrabold uppercase tracking-wide text-black">
              {t('overchargeBadge')}
            </span>
          )}
          <span
            className={`px-2 py-0.5 rounded font-semibold ${
              detail.status === 'pending'
                ? 'bg-yellow-500/20 text-yellow-300'
                : detail.status === 'approved'
                  ? 'bg-green-500/20 text-green-300'
                  : 'bg-gray-700 text-gray-300'
            }`}
          >
            {statusLabel}
          </span>
        </div>
      </header>

      <section className="bg-gray-900 border border-gray-800 rounded-xl p-4 space-y-3">
        <div>
          <h2 className="text-sm font-semibold text-white">{t('manualEditTitle')}</h2>
          <p className="text-xs text-gray-500 leading-relaxed mt-1">
            {detail.requestType === 'overcharge'
              ? t('overchargeEditDescription', { cap: formatSilver(detail.roleCap) })
              : t('manualEditDescription', { cap: formatSilver(detail.roleCap) })}
          </p>
          {detail.requestType === 'overcharge' && (
            <p className="mt-2 rounded-lg border border-orange-500/30 bg-orange-500/10 px-3 py-2 text-xs leading-relaxed text-orange-200">
              {t('overchargeNoKillboard')}
            </p>
          )}
        </div>

        <div className="space-y-1">
          <label htmlFor="manual-claim" className="block text-xs text-gray-400 font-semibold">
            {t('manualClaimLabel')}
          </label>
          <div className="flex items-center gap-2">
            <input
              id="manual-claim"
              type="text"
              inputMode="numeric"
              value={inputValue}
              onChange={(e) => setInputValue(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === 'Enter') {
                  e.preventDefault()
                  handleSaveClaim()
                }
              }}
              disabled={!editable || pending}
              className="flex-1 bg-gray-800 border border-gray-700 rounded px-3 py-2 text-sm text-white font-mono focus:outline-none focus:border-amber-500 disabled:opacity-60"
            />
            <span className="text-xs text-gray-500">{t('manualClaimUnit')}</span>
            {editable && (
              <button
                type="button"
                onClick={handleSaveClaim}
                disabled={pending}
                className="inline-flex items-center gap-1 bg-amber-500 hover:bg-amber-400 disabled:bg-gray-700 disabled:text-gray-500 text-black font-bold px-3 py-2 rounded text-sm"
              >
                {pending ? <Loader2 size={14} className="animate-spin" /> : <Save size={14} />}
                {pending ? t('manualSaving') : t('manualSave')}
              </button>
            )}
          </div>
          {error && <p className="text-red-400 text-xs">{error}</p>}
        </div>

        <div className="border-t border-gray-800 pt-3 space-y-1 text-xs">
          <div className="flex items-center justify-between">
            <span className="text-gray-500">{t('claimedLabelWithCap', { cap: formatSilver(detail.roleCap) })}</span>
            <span className="font-mono text-white">{formatSilver(claimedSilver)}s</span>
          </div>
          <div className="flex items-center justify-between">
            <span className="text-gray-500">{t('payoutLabel', { rate: detail.payoutRatePercent })}</span>
            <span className="font-mono font-bold text-amber-400">{formatSilver(expectedPayout)}p</span>
          </div>
        </div>
      </section>

      {!detail.autoGenerated && (
        <section className="bg-gray-900 border border-gray-800 rounded-xl p-4 space-y-3">
          <div>
            <h2 className="text-sm font-semibold text-white">{t('videoProofTitle')}</h2>
            <p className="text-xs text-gray-500 leading-relaxed mt-1">
              {t('videoProofDescription')}
            </p>
          </div>

          <div className="space-y-2">
            <label htmlFor="manual-video-proof" className="block text-xs text-gray-400 font-semibold">
              {t('videoProofLabel')}
            </label>
            <input
              id="manual-video-proof"
              type="url"
              inputMode="url"
              value={videoUrl}
              onChange={(e) => {
                setVideoUrl(e.target.value)
                setVideoError(null)
              }}
              disabled={!editable || videoPending}
              placeholder={t('videoProofPlaceholder')}
              className="w-full bg-gray-800 border border-gray-700 rounded px-3 py-2 text-sm text-white focus:outline-none focus:border-amber-500 disabled:opacity-60"
            />
            {savedVideoWatchUrl ? (
              <a
                href={savedVideoWatchUrl}
                target="_blank"
                rel="noopener noreferrer"
                className="inline-flex max-w-full items-center gap-1 text-xs text-sky-300 hover:text-sky-200"
                title={savedVideoLabel}
              >
                <ExternalLink size={12} className="shrink-0" />
                <span className="truncate">{savedVideoLabel}</span>
              </a>
            ) : (
              <p className="text-xs text-gray-500">{t('videoProofEmpty')}</p>
            )}
            {videoError && <p className="text-red-400 text-xs">{videoError}</p>}
          </div>

          {editable && (
            <div className="flex justify-end pt-1">
              <button
                type="button"
                onClick={handleSaveVideoProof}
                disabled={videoPending || !videoDirty}
                className="inline-flex items-center gap-1 bg-amber-500 hover:bg-amber-400 disabled:bg-gray-700 disabled:text-gray-500 text-black font-bold px-3 py-2 rounded text-sm"
              >
                {videoPending ? <Loader2 size={14} className="animate-spin" /> : <Save size={14} />}
                {videoPending ? t('videoProofSaving') : t('videoProofSave')}
              </button>
            </div>
          )}
        </section>
      )}

      {!detail.autoGenerated && (
        <section className="bg-gray-900 border border-gray-800 rounded-xl p-4 space-y-3">
          <div>
            <h2 className="text-sm font-semibold text-white">{t('screenshotEditTitle')}</h2>
            <p className="text-xs text-gray-500 leading-relaxed mt-1">
              {t('screenshotEditDescription')}
            </p>
          </div>

          <div className="space-y-4">
            <ScreenshotSlotEditor
              requestId={detail.id}
              slot="primary"
              label={t('screenshotPrimary')}
              state={primarySlot}
              editable={editable}
              onSelectFile={(file) =>
                setPrimarySlot((s) => ({ ...s, pendingFile: file, pendingRemove: false }))
              }
              onUndo={() =>
                setPrimarySlot((s) => ({ ...s, pendingFile: null, pendingRemove: false }))
              }
              canRemove={false}
              onRemoveCurrent={() => {}}
            />
            <ScreenshotSlotEditor
              requestId={detail.id}
              slot="secondary"
              label={t('screenshotSecondary')}
              state={secondarySlot}
              editable={editable}
              onSelectFile={(file) =>
                setSecondarySlot((s) => ({ ...s, pendingFile: file, pendingRemove: false }))
              }
              onUndo={() =>
                setSecondarySlot((s) => ({ ...s, pendingFile: null, pendingRemove: false }))
              }
              canRemove
              onRemoveCurrent={() =>
                setSecondarySlot((s) => ({ ...s, pendingRemove: true, pendingFile: null }))
              }
            />
          </div>

          {shotError && <p className="text-red-400 text-xs">{shotError}</p>}

          {editable && (
            <div className="flex justify-end pt-1">
              <button
                type="button"
                onClick={handleSaveScreenshots}
                disabled={shotPending || !hasShotChanges}
                className="inline-flex items-center gap-1 bg-amber-500 hover:bg-amber-400 disabled:bg-gray-700 disabled:text-gray-500 text-black font-bold px-3 py-2 rounded text-sm"
              >
                {shotPending ? <Loader2 size={14} className="animate-spin" /> : <Save size={14} />}
                {shotPending ? t('screenshotSaving') : t('screenshotSave')}
              </button>
            </div>
          )}
        </section>
      )}

      {detail.status === 'approved' && (
        <p className="text-gray-500 text-xs">{t('alreadyApproved')}</p>
      )}
      {detail.status === 'rejected' && (
        <p className="text-gray-500 text-xs">{t('alreadyRejected')}</p>
      )}
      {detail.rejectReasonCode && (
        <div className="bg-red-500/10 border border-red-500/30 rounded-lg p-3">
          <p className="text-xs text-red-300/80 mb-1">{tMe('rejectReasonLabel')}</p>
          <p className="text-sm text-red-200 font-semibold">{tReason(detail.rejectReasonCode)}</p>
        </div>
      )}
      {detail.adminNotes && (
        <div className="bg-gray-900 border border-gray-800 rounded-lg p-3">
          <p className="text-xs text-gray-500 mb-1">{t('adminNotesTitle')}</p>
          <p className="text-sm text-gray-300 whitespace-pre-wrap">{detail.adminNotes}</p>
        </div>
      )}
    </div>
  )
}

interface ScreenshotSlotEditorProps {
  requestId: string
  slot: SlotKind
  label: string
  state: ScreenshotSlotState
  editable: boolean
  canRemove: boolean
  onSelectFile: (file: File) => void
  onRemoveCurrent: () => void
  onUndo: () => void
}

function ScreenshotSlotEditor({
  requestId,
  slot,
  label,
  state,
  editable,
  canRemove,
  onSelectFile,
  onRemoveCurrent,
  onUndo,
}: ScreenshotSlotEditorProps) {
  const t = useTranslations('regearBreakdown')
  const inputRef = useRef<HTMLInputElement>(null)
  const inputId = `manual-regear-shot-${slot}`
  const [dragging, setDragging] = useState(false)

  // 새로 선택한 파일의 로컬 미리보기 — useMemo 로 동기 계산 후 useEffect 에서
  // 정리. 효과 본문에서 setState 를 호출하면 cascading render 경고가 난다.
  const pendingPreview = useMemo(
    () => (state.pendingFile ? URL.createObjectURL(state.pendingFile) : null),
    [state.pendingFile],
  )
  useEffect(() => {
    if (!pendingPreview) return
    return () => URL.revokeObjectURL(pendingPreview)
  }, [pendingPreview])

  // 현재 저장된 스크린샷의 signed URL — currentPath 가 바뀌면 다시 fetch.
  // setState 는 async then/catch 안에서만 호출 (효과 본문에서 직접 호출하지 않음).
  // currentPath 가 바뀌었는데 새 fetch 가 아직 끝나지 않은 시점엔 byPath.path !==
  // state.currentPath 이므로 derived 값에서 null 로 떨어진다.
  const [byPath, setByPath] = useState<{
    path: string | null
    url: string | null
    error: boolean
  }>({ path: null, url: null, error: false })

  useEffect(() => {
    const path = state.currentPath
    if (!path) return
    let cancelled = false
    getMyRegearScreenshotUrl(requestId, slot)
      .then((res) => {
        if (cancelled) return
        setByPath({ path, url: res.url ?? null, error: !res.url })
      })
      .catch(() => {
        if (cancelled) return
        setByPath({ path, url: null, error: true })
      })
    return () => {
      cancelled = true
    }
  }, [requestId, slot, state.currentPath])

  const currentUrl = byPath.path === state.currentPath ? byPath.url : null
  const currentLoadError =
    byPath.path === state.currentPath && byPath.error

  const onFiles = (files: FileList | null) => {
    const file = files?.[0]
    if (!file) return
    if (!ACCEPTED_TYPES.includes(file.type)) return
    compressImageIfLarge(file).then(onSelectFile)
  }

  const showPending = state.pendingFile !== null
  const showCurrent = !showPending && state.currentPath !== null && !state.pendingRemove
  const showEmpty =
    !showPending && (state.currentPath === null || state.pendingRemove)

  return (
    <div className="space-y-2">
      <div className="flex items-center justify-between gap-2">
        <span className="text-[11px] font-semibold text-gray-400">{label}</span>
        {showPending && (
          <span className="inline-flex items-center gap-1 text-[10px] text-amber-300 bg-amber-500/15 border border-amber-500/30 px-2 py-0.5 rounded-full">
            {t('screenshotPending')}
          </span>
        )}
        {!showPending && state.pendingRemove && (
          <span className="inline-flex items-center gap-1 text-[10px] text-rose-300 bg-rose-500/15 border border-rose-500/30 px-2 py-0.5 rounded-full">
            {t('screenshotPendingRemove')}
          </span>
        )}
      </div>

      {showCurrent && (
        <div className="rounded-lg border border-gray-700 bg-gray-950 overflow-hidden">
          {currentUrl ? (
            // eslint-disable-next-line @next/next/no-img-element
            <img
              src={currentUrl}
              alt={t('screenshotAlt')}
              className="w-full max-h-72 object-contain bg-black"
            />
          ) : currentLoadError ? (
            <div className="flex items-center justify-center text-xs text-gray-500 py-10">
              {t('screenshotLoadError')}
            </div>
          ) : (
            <div className="flex items-center justify-center text-xs text-gray-500 py-10">
              <Loader2 size={14} className="animate-spin" />
            </div>
          )}
        </div>
      )}

      {showPending && pendingPreview && (
        <div className="rounded-lg border border-amber-500/40 bg-gray-950 overflow-hidden">
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            src={pendingPreview}
            alt={t('screenshotAlt')}
            className="w-full max-h-72 object-contain bg-black"
          />
        </div>
      )}

      {showEmpty && (
        <div className="flex items-center justify-center text-xs text-gray-500 py-6 border border-dashed border-gray-700 rounded-lg">
          {t('screenshotMissing')}
        </div>
      )}

      {editable && (
        <>
          <label
            htmlFor={inputId}
            onDragOver={(e) => {
              e.preventDefault()
              setDragging(true)
            }}
            onDragLeave={() => setDragging(false)}
            onDrop={(e) => {
              e.preventDefault()
              setDragging(false)
              onFiles(e.dataTransfer.files)
            }}
            className={`flex flex-col items-center justify-center gap-1 w-full rounded-lg cursor-pointer transition-colors py-3 border border-dashed text-xs ${
              dragging
                ? 'border-amber-500 text-amber-400 bg-gray-800'
                : 'border-gray-600 hover:border-amber-500 text-gray-400 hover:text-amber-400 bg-gray-800/50'
            }`}
          >
            <Upload size={14} />
            <span>{t('screenshotPick')}</span>
            <span className="inline-flex items-center gap-1 text-[10px] text-gray-500">
              <Clipboard size={10} />
              {t('screenshotPasteHint')}
            </span>
          </label>
          <input
            id={inputId}
            ref={inputRef}
            type="file"
            accept="image/png,image/jpeg,image/webp"
            className="hidden"
            onChange={(e) => onFiles(e.target.files)}
          />

          <div className="flex items-center justify-end gap-2 text-[11px]">
            {(showPending || state.pendingRemove) && (
              <button
                type="button"
                onClick={onUndo}
                className="inline-flex items-center gap-1 text-gray-400 hover:text-white"
              >
                <Undo2 size={12} />
                {t('screenshotUndo')}
              </button>
            )}
            {canRemove && state.currentPath && !state.pendingRemove && !showPending && (
              <button
                type="button"
                onClick={onRemoveCurrent}
                className="inline-flex items-center gap-1 text-gray-400 hover:text-rose-400"
              >
                <Trash2 size={12} />
                {t('screenshotRemove')}
              </button>
            )}
          </div>
        </>
      )}
    </div>
  )
}
