'use client'

// 자동 생성 리기어 pending 상태에서 청구자가 부위별 단위 시세를 정정하는
// 인라인 편집기. 승인된 행이나 수동 제출 행은 read-only 모드로 렌더링.
//
// 흐름: 슬롯 input 값 편집 → Enter / blur → Server Action 호출 → router.refresh().
// optimistic update 은 하지 않는다 — 서버가 market/claimed/payout 을 재계산해서
// 돌려주므로 그 값으로 화면을 갱신한다. 단일 요청만 in-flight 를 허용해
// 빠른 연속 편집 시에도 race 없이 일관된 상태로 수렴.

import { useState, useTransition } from 'react'
import { useRouter } from 'next/navigation'
import { Save, Loader2, Pencil } from 'lucide-react'
import {
  updateMyRegearLineItemPrice,
  type MyRegearDetail,
  type RegearLineItem,
} from '@/app/actions/regear'
import { formatSilver, parseSilverInput } from '@/lib/silver'
import { calcPayoutSilver } from '@/lib/regear-payout'
import ItemImage from './ItemImage'

interface Props {
  detail: MyRegearDetail
}

const WARNING_BADGE: Record<string, { label: string; className: string }> = {
  quality: { label: '품질 낮춤', className: 'bg-yellow-500/20 text-yellow-300' },
  window: { label: '기간 확장', className: 'bg-yellow-500/20 text-yellow-300' },
  bluezone: { label: '블루존 확장', className: 'bg-orange-500/20 text-orange-300' },
  redzone: { label: '레드존 확장', className: 'bg-red-500/20 text-red-300' },
}

function buildItemId(uniqueName: string, enchant: number): string {
  return enchant > 0 ? `${uniqueName}@${enchant}` : uniqueName
}

function lineSubtotal(item: RegearLineItem): number {
  if (!item.price || item.price <= 0) return 0
  return item.price * item.count
}

export default function MyRegearBreakdownEditor({ detail }: Props) {
  const router = useRouter()
  const [items, setItems] = useState<RegearLineItem[]>(detail.items)
  const [marketSilver, setMarketSilver] = useState<number>(detail.marketSilver)
  const [claimedSilver, setClaimedSilver] = useState<number>(detail.claimedSilver)
  const [payoutSilver, setPayoutSilver] = useState<number>(detail.payoutSilver ?? 0)
  const [editing, setEditing] = useState<{ slot: string; value: string } | null>(null)
  const [rowError, setRowError] = useState<{ slot: string; message: string } | null>(null)
  const [pending, startTransition] = useTransition()
  const [savingSlot, setSavingSlot] = useState<string | null>(null)

  const editable = detail.status === 'pending' && detail.autoGenerated
  const warning = detail.warningLevel ? WARNING_BADGE[detail.warningLevel] : null

  const handleStartEdit = (item: RegearLineItem) => {
    if (!editable) return
    setEditing({ slot: item.slot, value: (item.price ?? 0).toString() })
    setRowError(null)
  }

  const handleCancel = () => {
    setEditing(null)
    setRowError(null)
  }

  const handleSave = (slot: string) => {
    if (!editing || editing.slot !== slot) return
    const parsed = parseSilverInput(editing.value)
    if (parsed === null) {
      setRowError({ slot, message: '유효한 숫자를 입력하세요.' })
      return
    }
    setRowError(null)
    setSavingSlot(slot)
    startTransition(async () => {
      const result = await updateMyRegearLineItemPrice(detail.id, slot, parsed)
      setSavingSlot(null)
      if (result.error) {
        setRowError({ slot, message: result.error })
        return
      }
      setItems((prev) =>
        prev.map((it) => (it.slot === slot ? { ...it, price: parsed, userEdited: true } : it)),
      )
      if (typeof result.marketSilver === 'number') setMarketSilver(result.marketSilver)
      if (typeof result.claimedSilver === 'number') setClaimedSilver(result.claimedSilver)
      if (typeof result.payoutSilver === 'number') setPayoutSilver(result.payoutSilver)
      setEditing(null)
      router.refresh()
    })
  }

  // claimed/payout 는 서버가 재계산하지만, 표시 일관성을 위해 클라에서도 동일
  // 공식으로 미리 계산된 payout 을 비교에 쓴다.
  const expectedPayout = calcPayoutSilver(claimedSilver, detail.payoutRatePercent)

  return (
    <div className="space-y-4">
      <header className="bg-gray-900 border border-gray-800 rounded-xl p-4 space-y-2">
        <h1 className="text-lg font-bold text-white">{detail.eventTitle}</h1>
        <div className="flex items-center flex-wrap gap-2 text-xs text-gray-400">
          <span className="bg-gray-800 px-2 py-0.5 rounded">{detail.roleName}</span>
          <span
            className={`px-2 py-0.5 rounded font-semibold ${
              detail.status === 'pending'
                ? 'bg-yellow-500/20 text-yellow-300'
                : detail.status === 'approved'
                  ? 'bg-green-500/20 text-green-300'
                  : 'bg-gray-700 text-gray-300'
            }`}
          >
            {detail.status === 'pending' ? '승인 대기' : detail.status === 'approved' ? '승인됨' : '반려됨'}
          </span>
          {detail.autoGenerated && (
            <span className="bg-blue-500/20 text-blue-300 px-2 py-0.5 rounded">자동 생성</span>
          )}
          {warning && (
            <span className={`px-2 py-0.5 rounded ${warning.className}`}>시세 {warning.label}</span>
          )}
        </div>
        {editable && (
          <p className="text-gray-500 text-xs leading-relaxed">
            승인 전까지 부위별 단위 시세를 수정할 수 있습니다. 입력한 값 × 수량 = 해당 부위 청구액이 되고,
            청구 합계는 역할 상한 <span className="font-mono text-gray-300">{formatSilver(detail.roleCap)}s</span> 로
            클램프됩니다. 지급 예정은 청구액의 <span className="font-mono text-gray-300">{detail.payoutRatePercent}%</span>.
          </p>
        )}
      </header>

      <section className="bg-gray-900 border border-gray-800 rounded-xl overflow-hidden">
        <table className="w-full text-sm">
          <thead>
            <tr className="bg-gray-950 text-xs text-gray-400 uppercase tracking-wide">
              <th className="text-left px-3 py-2 font-semibold">슬롯</th>
              <th className="text-left px-3 py-2 font-semibold">아이템</th>
              <th className="text-right px-3 py-2 font-semibold">수량</th>
              <th className="text-right px-3 py-2 font-semibold">단위 시세</th>
              <th className="text-right px-3 py-2 font-semibold">소계</th>
            </tr>
          </thead>
          <tbody>
            {items.length === 0 ? (
              <tr>
                <td colSpan={5} className="text-center text-gray-500 text-sm py-6">
                  장비 데이터가 없습니다.
                </td>
              </tr>
            ) : (
              items.map((it) => {
                const isEditingRow = editing?.slot === it.slot
                const isSaving = savingSlot === it.slot
                const itemId = buildItemId(it.uniqueName, it.enchant)
                return (
                  <tr key={it.slot} className="border-t border-gray-800">
                    <td className="px-3 py-2 text-gray-400 font-mono text-xs">{it.slot}</td>
                    <td className="px-3 py-2">
                      <div className="flex items-center gap-2 min-w-0">
                        <ItemImage itemId={itemId} itemName={it.uniqueName} size={36} />
                        <div className="min-w-0">
                          <p className="text-white text-xs truncate">{it.uniqueName}</p>
                          <p className="text-gray-500 text-[10px]">
                            {it.enchant > 0 ? `+${it.enchant} · ` : ''}Q{it.quality}
                            {it.city && <span className="ml-1 text-gray-600">· {it.city}</span>}
                            {it.userEdited && (
                              <span className="ml-2 text-amber-400 font-semibold">직접 수정</span>
                            )}
                          </p>
                        </div>
                      </div>
                    </td>
                    <td className="px-3 py-2 text-right text-gray-300 font-mono text-xs">× {it.count}</td>
                    <td className="px-3 py-2 text-right">
                      {isEditingRow ? (
                        <div className="flex items-center justify-end gap-1">
                          <input
                            type="text"
                            inputMode="numeric"
                            value={editing!.value}
                            autoFocus
                            onChange={(e) =>
                              setEditing({ slot: it.slot, value: e.target.value })
                            }
                            onKeyDown={(e) => {
                              if (e.key === 'Enter') handleSave(it.slot)
                              if (e.key === 'Escape') handleCancel()
                            }}
                            onBlur={() => handleSave(it.slot)}
                            disabled={isSaving || pending}
                            className="w-28 bg-gray-800 border border-gray-700 rounded px-2 py-1 text-xs text-white text-right font-mono focus:outline-none focus:border-amber-500"
                          />
                          <button
                            type="button"
                            onMouseDown={(e) => {
                              e.preventDefault()
                              handleSave(it.slot)
                            }}
                            disabled={isSaving || pending}
                            className="bg-amber-500 hover:bg-amber-400 disabled:bg-gray-700 text-black p-1 rounded"
                          >
                            {isSaving ? <Loader2 size={12} className="animate-spin" /> : <Save size={12} />}
                          </button>
                        </div>
                      ) : (
                        <button
                          type="button"
                          onClick={() => handleStartEdit(it)}
                          disabled={!editable}
                          className={`inline-flex items-center gap-1 font-mono text-xs ${
                            editable
                              ? 'text-white hover:bg-gray-800 px-2 py-1 rounded'
                              : 'text-gray-300 cursor-default'
                          }`}
                          title={editable ? '클릭해서 수정' : undefined}
                        >
                          {it.price === null ? (
                            <span className="text-gray-500">미산정</span>
                          ) : (
                            <span>{formatSilver(it.price)}s</span>
                          )}
                          {editable && <Pencil size={10} className="text-gray-500" />}
                        </button>
                      )}
                      {rowError && rowError.slot === it.slot && (
                        <p className="text-red-400 text-[11px] mt-1">{rowError.message}</p>
                      )}
                    </td>
                    <td className="px-3 py-2 text-right font-mono text-amber-300 text-xs">
                      {lineSubtotal(it) > 0 ? `${formatSilver(lineSubtotal(it))}s` : '—'}
                    </td>
                  </tr>
                )
              })
            )}
          </tbody>
          <tfoot>
            <tr className="border-t-2 border-gray-700 bg-gray-950">
              <td colSpan={4} className="px-3 py-2 text-right text-xs text-gray-400">
                시장가 합계
              </td>
              <td className="px-3 py-2 text-right font-mono text-white">
                {formatSilver(marketSilver)}s
              </td>
            </tr>
            <tr className="bg-gray-950">
              <td colSpan={4} className="px-3 py-2 text-right text-xs text-gray-400">
                청구액 (상한 {formatSilver(detail.roleCap)}s 로 클램프)
              </td>
              <td className="px-3 py-2 text-right font-mono text-white">
                {formatSilver(claimedSilver)}s
              </td>
            </tr>
            <tr className="bg-gray-950">
              <td colSpan={4} className="px-3 py-2 text-right text-xs text-gray-400">
                지급 예정 ({detail.payoutRatePercent}%)
              </td>
              <td className="px-3 py-2 text-right font-mono font-bold text-amber-400">
                {formatSilver(payoutSilver || expectedPayout)}p
              </td>
            </tr>
          </tfoot>
        </table>
      </section>

      {!editable && detail.status === 'pending' && !detail.autoGenerated && (
        <p className="text-gray-500 text-xs">수동 제출된 리기어는 이 페이지에서 수정할 수 없습니다.</p>
      )}
      {detail.status !== 'pending' && (
        <p className="text-gray-500 text-xs">이미 {detail.status === 'approved' ? '승인' : '반려'}된 리기어는 수정할 수 없습니다.</p>
      )}
      {detail.adminNotes && (
        <div className="bg-gray-900 border border-gray-800 rounded-lg p-3">
          <p className="text-xs text-gray-500 mb-1">관리자 메모</p>
          <p className="text-sm text-gray-300 whitespace-pre-wrap">{detail.adminNotes}</p>
        </div>
      )}
    </div>
  )
}
