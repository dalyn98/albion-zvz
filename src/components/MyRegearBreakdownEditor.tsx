'use client'

// 자동 생성 리기어 pending 상태에서 청구자가 부위별 단위 시세를 정정하는
// 인라인 편집기. 승인된 행이나 수동 제출 행은 read-only 모드로 렌더링.
//
// 흐름: 슬롯 input 값 편집 → Enter / blur → Server Action 호출 → router.refresh().
// optimistic update 은 하지 않는다 — 서버가 market/claimed/payout 을 재계산해서
// 돌려주므로 그 값으로 화면을 갱신한다. 단일 요청만 in-flight 를 허용해
// 빠른 연속 편집 시에도 race 없이 일관된 상태로 수렴.

import { useState, useTransition } from 'react'
import { useRouter } from 'next/navigation'
import { useLocale, useTranslations } from 'next-intl'
import { Save, Loader2, Pencil } from 'lucide-react'
import { type MyRegearDetail, type RegearLineItem } from '@/app/actions/regear'
import { updateMyRegearLineItemPrice } from '@/app/actions/regear-edit'
import { formatSilver, parseSilverInput } from '@/lib/silver'
import { calcPayoutSilver } from '@/lib/regear-payout'
import { useItemNameResolver } from '@/lib/item-names-client'
import { translateSlotRole } from '@/lib/slot-role-i18n'
import type { Locale } from '@/i18n/locales'
import { SLOT_KEYS, type SlotKey } from '@/types'
import ItemImage from './ItemImage'
import MyRegearBuildSnapshotEditor from './MyRegearBuildSnapshotEditor'
import { useReportDirty } from './UnsavedChangesProvider'
import { useToast } from './ToastProvider'

interface Props {
  detail: MyRegearDetail
}

function SummaryMetric({ label, value, accent = false }: { label: string; value: string; accent?: boolean }) {
  return (
    <div>
      <dt className="line-clamp-2 text-[10px] text-gray-500">{label}</dt>
      <dd className={`mt-1 font-mono text-xs font-semibold ${accent ? 'text-amber-400' : 'text-white'}`}>{value}</dd>
    </div>
  )
}

type WarningKey = 'quality' | 'window' | 'bluezone' | 'redzone'

const WARNING_CLASS: Record<WarningKey, string> = {
  quality: 'bg-yellow-500/20 text-yellow-300',
  window: 'bg-yellow-500/20 text-yellow-300',
  bluezone: 'bg-orange-500/20 text-orange-300',
  redzone: 'bg-red-500/20 text-red-300',
}

function buildItemId(uniqueName: string, enchant: number): string {
  return enchant > 0 ? `${uniqueName}@${enchant}` : uniqueName
}

function lineSubtotal(item: RegearLineItem): number {
  if (!item.price || item.price <= 0) return 0
  return item.price * item.count
}

export default function MyRegearBreakdownEditor({ detail }: Props) {
  const router = useRouter()
  const toast = useToast()
  const t = useTranslations('regearBreakdown')
  const tMe = useTranslations('me')
  const tReason = useTranslations('regearRejectReason')
  const tRole = useTranslations('slotRole')
  const tGear = useTranslations('gear')
  const locale = useLocale() as Locale
  const { getLocalizedItemName } = useItemNameResolver(locale)
  const [items, setItems] = useState<RegearLineItem[]>(detail.items)
  const [marketSilver, setMarketSilver] = useState<number>(detail.marketSilver)
  const [claimedSilver, setClaimedSilver] = useState<number>(detail.claimedSilver)
  const [payoutSilver, setPayoutSilver] = useState<number>(detail.payoutSilver ?? 0)
  const [editing, setEditing] = useState<{ slot: string; value: string } | null>(null)
  const [rowError, setRowError] = useState<{ slot: string; message: string } | null>(null)
  const [pending, startTransition] = useTransition()
  const [savingSlot, setSavingSlot] = useState<string | null>(null)

  const editable = detail.status === 'pending' && detail.autoGenerated
  const showBuildSnapshotEditor =
    detail.fulfillmentMode === 'crafted' && detail.autoGenerated

  // 미저장 변경 가드 — 슬롯 인라인 편집 중(editing !== null)에 입력값이 원본과
  // 다르면 dirty. blur/Enter 시 즉시 저장되는 흐름이라 dirty 창이 짧지만,
  // 입력하다 다른 탭으로 가버리는 모서리 케이스를 막는다.
  const editingItem = editing ? items.find((it) => it.slot === editing.slot) : null
  const isDirty =
    editable &&
    editing !== null &&
    editingItem != null &&
    editing.value !== (editingItem.price ?? 0).toString()
  useReportDirty(`me-regear-breakdown:${detail.id}`, isDirty)
  const warningKey: WarningKey | null = detail.warningLevel
  const lowConfidenceCount = items.filter((it) => it.confidence === 'low' && !it.userEdited).length

  const warningLabel = (() => {
    if (!warningKey) return null
    if (warningKey === 'quality') return t('warningBadgeQuality')
    if (warningKey === 'window') return t('warningBadgeWindow')
    if (warningKey === 'bluezone') return t('warningBadgeBluezone')
    return t('warningBadgeRedzone')
  })()

  const handleStartEdit = (item: RegearLineItem) => {
    if (!editable) return
    setEditing({ slot: item.slot, value: (item.price ?? 0).toString() })
    setRowError(null)
  }

  const handleCancel = () => {
    setEditing(null)
    setRowError(null)
  }

  const handleSave = (slot: string) => {
    if (!editing || editing.slot !== slot) return
    const parsed = parseSilverInput(editing.value)
    if (parsed === null) {
      setRowError({ slot, message: t('invalidNumber') })
      return
    }
    setRowError(null)
    setSavingSlot(slot)
    startTransition(async () => {
      const result = await updateMyRegearLineItemPrice(detail.id, slot, parsed)
      setSavingSlot(null)
      if (result.error) {
        setRowError({ slot, message: result.error })
        toast.error(result.error)
        return
      }
      setItems((prev) =>
        prev.map((it) => (it.slot === slot ? { ...it, price: parsed, userEdited: true } : it)),
      )
      if (typeof result.marketSilver === 'number') setMarketSilver(result.marketSilver)
      if (typeof result.claimedSilver === 'number') setClaimedSilver(result.claimedSilver)
      if (typeof result.payoutSilver === 'number') setPayoutSilver(result.payoutSilver)
      setEditing(null)
      toast.success(t('priceSavedToast'))
      router.refresh()
    })
  }

  const renderPriceControl = (item: RegearLineItem, align: 'left' | 'right' = 'right') => {
    const isEditingRow = editing?.slot === item.slot
    const isSaving = savingSlot === item.slot
    const alignment = align === 'left' ? 'justify-start' : 'justify-end'
    return (
      <div>
        {isEditingRow ? (
          <div className={`flex ${alignment} gap-1`}>
            <input
              type="text"
              inputMode="numeric"
              value={editing!.value}
              autoFocus
              onChange={(event) => setEditing({ slot: item.slot, value: event.target.value })}
              onKeyDown={(event) => {
                if (event.key === 'Enter') handleSave(item.slot)
                if (event.key === 'Escape') handleCancel()
              }}
              onBlur={() => handleSave(item.slot)}
              disabled={isSaving || pending}
              className="w-28 bg-gray-800 border border-gray-700 rounded px-2 py-1 text-xs text-white text-right font-mono focus:outline-none focus:border-amber-500"
            />
            <button
              type="button"
              onMouseDown={(event) => {
                event.preventDefault()
                handleSave(item.slot)
              }}
              disabled={isSaving || pending}
              className="bg-amber-500 hover:bg-amber-400 disabled:bg-gray-700 text-black p-1 rounded"
            >
              {isSaving ? <Loader2 size={12} className="animate-spin" /> : <Save size={12} />}
            </button>
          </div>
        ) : (
          <button
            type="button"
            onClick={() => handleStartEdit(item)}
            disabled={!editable}
            className={`inline-flex items-center gap-1 font-mono text-xs ${
              editable
                ? 'text-white hover:bg-gray-800 px-2 py-1 rounded'
                : 'text-gray-300 cursor-default'
            }`}
            title={editable ? t('editHint') : undefined}
          >
            {item.price === null ? (
              <span className="text-gray-500">{t('priceUnassigned')}</span>
            ) : (
              <span>{formatSilver(item.price)}s</span>
            )}
            {editable && <Pencil size={10} className="text-gray-500" />}
          </button>
        )}
        {rowError && rowError.slot === item.slot && (
          <p className="text-red-400 text-[11px] mt-1">{rowError.message}</p>
        )}
      </div>
    )
  }

  // claimed/payout 는 서버가 재계산하지만, 표시 일관성을 위해 클라에서도 동일
  // 공식으로 미리 계산된 payout 을 비교에 쓴다.
  const expectedPayout = calcPayoutSilver(claimedSilver, detail.payoutRatePercent)

  const statusLabel =
    detail.status === 'pending'
      ? t('statusPending')
      : detail.status === 'approved'
        ? t('statusApproved')
        : t('statusRejected')

  return (
    <div className="space-y-4">
      <header className="bg-gray-900 border border-gray-800 rounded-xl p-4 space-y-2">
        <h1 className="text-lg font-bold text-white">{detail.eventTitle}</h1>
        <div className="flex items-center flex-wrap gap-2 text-xs text-gray-400">
          <span className="bg-gray-800 px-2 py-0.5 rounded">
            {translateSlotRole(detail.roleName, tRole)}
          </span>
          <span
            className={`px-2 py-0.5 rounded font-semibold ${
              detail.status === 'pending'
                ? 'bg-yellow-500/20 text-yellow-300'
                : detail.status === 'approved'
                  ? 'bg-green-500/20 text-green-300'
                  : 'bg-gray-700 text-gray-300'
            }`}
          >
            {statusLabel}
          </span>
          {detail.autoGenerated && (
            <span className="bg-blue-500/20 text-blue-300 px-2 py-0.5 rounded">{t('autoGeneratedBadge')}</span>
          )}
          {warningKey && warningLabel && (
            <span className={`px-2 py-0.5 rounded ${WARNING_CLASS[warningKey]}`}>{warningLabel}</span>
          )}
        </div>
        {editable && (
          <p className="text-gray-500 text-xs leading-relaxed">
            {t('editableHint', {
              cap: formatSilver(detail.roleCap),
              rate: detail.payoutRatePercent,
            })}
          </p>
        )}
        {editable && lowConfidenceCount > 0 && (
          <p className="text-orange-400 text-xs leading-relaxed bg-orange-500/10 border border-orange-500/30 rounded px-2 py-1.5">
            {t('lowConfidenceHint', { count: lowConfidenceCount })}
          </p>
        )}
      </header>

      <section className="space-y-2 sm:hidden">
        {items.length === 0 ? (
          <p className="rounded-xl border border-gray-800 bg-gray-900 px-4 py-6 text-center text-sm text-gray-500">
            {t('noEquipment')}
          </p>
        ) : (
          items.map((item) => {
            const itemId = buildItemId(item.uniqueName, item.enchant)
            const displayName = getLocalizedItemName(item.uniqueName, locale, item.uniqueName) ?? item.uniqueName
            const slotLabel = SLOT_KEYS.includes(item.slot as SlotKey) ? tGear(item.slot as SlotKey) : item.slot
            return (
              <article key={item.slot} className="rounded-xl border border-gray-800 bg-gray-900 p-3 space-y-3">
                <div className="flex items-start gap-2">
                  <ItemImage itemId={itemId} itemName={displayName} size={36} />
                  <div className="min-w-0 flex-1">
                    <p className="text-[11px] font-semibold text-gray-500">{slotLabel}</p>
                    <p className="truncate text-sm font-semibold text-white">{displayName}</p>
                    <p className="text-[10px] text-gray-500">
                      {item.enchant > 0 ? `+${item.enchant} · ` : ''}Q{item.quality}
                      {item.city && <span className="ml-1">· {item.city}</span>}
                      {item.userEdited && <span className="ml-2 font-semibold text-amber-400">{t('userEditedLabel')}</span>}
                      {!item.userEdited && item.confidence === 'low' && <span className="ml-2 font-semibold text-orange-400">{t('lowConfidenceLabel')}</span>}
                    </p>
                  </div>
                </div>
                <dl className="grid grid-cols-3 gap-2 border-t border-gray-800 pt-3 text-xs">
                  <div>
                    <dt className="text-gray-500">{t('countHeader')}</dt>
                    <dd className="mt-1 font-mono text-gray-200">× {item.count}</dd>
                  </div>
                  <div>
                    <dt className="text-gray-500">{t('unitPriceHeader')}</dt>
                    <dd className="mt-1">{renderPriceControl(item, 'left')}</dd>
                  </div>
                  <div>
                    <dt className="text-gray-500">{t('subtotalHeader')}</dt>
                    <dd className="mt-1 font-mono text-amber-300">{lineSubtotal(item) > 0 ? `${formatSilver(lineSubtotal(item))}s` : '—'}</dd>
                  </div>
                </dl>
              </article>
            )
          })
        )}
        <dl className="grid grid-cols-3 gap-2 rounded-xl border border-gray-800 bg-gray-950 p-3 text-xs">
          <SummaryMetric label={t('marketTotalLabel')} value={`${formatSilver(marketSilver)}s`} />
          <SummaryMetric label={t('claimedLabelWithCap', { cap: formatSilver(detail.roleCap) })} value={`${formatSilver(claimedSilver)}s`} />
          <SummaryMetric label={t('payoutLabel', { rate: detail.payoutRatePercent })} value={`${formatSilver(payoutSilver || expectedPayout)}p`} accent />
        </dl>
      </section>

      <section className="hidden overflow-x-auto rounded-xl border border-gray-800 bg-gray-900 sm:block">
        <table className="w-full min-w-[480px] text-sm">
          <thead>
            <tr className="bg-gray-950 text-xs text-gray-400 uppercase tracking-wide">
              <th className="text-left px-3 py-2 font-semibold">{t('slotHeader')}</th>
              <th className="text-left px-3 py-2 font-semibold">{t('itemHeader')}</th>
              <th className="text-right px-3 py-2 font-semibold">{t('countHeader')}</th>
              <th className="text-right px-3 py-2 font-semibold">{t('unitPriceHeader')}</th>
              <th className="text-right px-3 py-2 font-semibold">{t('subtotalHeader')}</th>
            </tr>
          </thead>
          <tbody>
            {items.length === 0 ? (
              <tr>
                <td colSpan={5} className="text-center text-gray-500 text-sm py-6">
                  {t('noEquipment')}
                </td>
              </tr>
            ) : (
              items.map((it) => {
                const itemId = buildItemId(it.uniqueName, it.enchant)
                const displayName =
                  getLocalizedItemName(it.uniqueName, locale, it.uniqueName) ?? it.uniqueName
                const slotLabel = SLOT_KEYS.includes(it.slot as SlotKey)
                  ? tGear(it.slot as SlotKey)
                  : it.slot
                return (
                  <tr key={it.slot} className="border-t border-gray-800">
                    <td className="px-3 py-2 text-gray-400 text-xs">{slotLabel}</td>
                    <td className="px-3 py-2">
                      <div className="flex items-center gap-2 min-w-0">
                        <ItemImage itemId={itemId} itemName={displayName} size={36} />
                        <div className="min-w-0">
                          <p className="text-white text-xs truncate">{displayName}</p>
                          <p className="text-gray-500 text-[10px]">
                            {it.enchant > 0 ? `+${it.enchant} · ` : ''}Q{it.quality}
                            {it.city && <span className="ml-1 text-gray-600">· {it.city}</span>}
                            {it.userEdited && (
                              <span className="ml-2 text-amber-400 font-semibold">{t('userEditedLabel')}</span>
                            )}
                            {!it.userEdited && it.confidence === 'low' && (
                              <span className="ml-2 text-orange-400 font-semibold">
                                {t('lowConfidenceLabel')}
                              </span>
                            )}
                          </p>
                        </div>
                      </div>
                    </td>
                    <td className="px-3 py-2 text-right text-gray-300 font-mono text-xs">× {it.count}</td>
                    <td className="px-3 py-2 text-right">
                      {renderPriceControl(it)}
                    </td>
                    <td className="px-3 py-2 text-right font-mono text-amber-300 text-xs">
                      {lineSubtotal(it) > 0 ? `${formatSilver(lineSubtotal(it))}s` : '—'}
                    </td>
                  </tr>
                )
              })
            )}
          </tbody>
          <tfoot>
            <tr className="border-t-2 border-gray-700 bg-gray-950">
              <td colSpan={4} className="px-3 py-2 text-right text-xs text-gray-400">
                {t('marketTotalLabel')}
              </td>
              <td className="px-3 py-2 text-right font-mono text-white">
                {formatSilver(marketSilver)}s
              </td>
            </tr>
            <tr className="bg-gray-950">
              <td colSpan={4} className="px-3 py-2 text-right text-xs text-gray-400">
                {t('claimedLabelWithCap', { cap: formatSilver(detail.roleCap) })}
              </td>
              <td className="px-3 py-2 text-right font-mono text-white">
                {formatSilver(claimedSilver)}s
              </td>
            </tr>
            <tr className="bg-gray-950">
              <td colSpan={4} className="px-3 py-2 text-right text-xs text-gray-400">
                {t('payoutLabel', { rate: detail.payoutRatePercent })}
              </td>
              <td className="px-3 py-2 text-right font-mono font-bold text-amber-400">
                {formatSilver(payoutSilver || expectedPayout)}p
              </td>
            </tr>
          </tfoot>
        </table>
      </section>

      {showBuildSnapshotEditor && (
        <MyRegearBuildSnapshotEditor
          requestId={detail.id}
          buildSnapshot={detail.buildSnapshot}
          roleName={detail.roleName}
          editable={editable}
        />
      )}

      {!editable && detail.status === 'pending' && !detail.autoGenerated && (
        <p className="text-gray-500 text-xs">{t('manualReadonly')}</p>
      )}
      {detail.status === 'approved' && (
        <p className="text-gray-500 text-xs">{t('alreadyApproved')}</p>
      )}
      {detail.status === 'rejected' && (
        <p className="text-gray-500 text-xs">{t('alreadyRejected')}</p>
      )}
      {detail.rejectReasonCode && (
        <div className="bg-red-500/10 border border-red-500/30 rounded-lg p-3">
          <p className="text-xs text-red-300/80 mb-1">{tMe('rejectReasonLabel')}</p>
          <p className="text-sm text-red-200 font-semibold">{tReason(detail.rejectReasonCode)}</p>
        </div>
      )}
      {detail.adminNotes && (
        <div className="bg-gray-900 border border-gray-800 rounded-lg p-3">
          <p className="text-xs text-gray-500 mb-1">{t('adminNotesTitle')}</p>
          <p className="text-sm text-gray-300 whitespace-pre-wrap">{detail.adminNotes}</p>
        </div>
      )}
    </div>
  )
}
