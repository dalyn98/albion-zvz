import Link from 'next/link'
import { notFound, redirect } from 'next/navigation'
import { ArrowLeft } from 'lucide-react'
import { getTranslations } from 'next-intl/server'
import { getSession } from '@/lib/session'
import { getMyRegearDetail } from '@/app/actions/regear'
import MyRegearBreakdownEditor from '@/components/MyRegearBreakdownEditor'
import MyManualRegearEditor from '@/components/MyManualRegearEditor'
import { getSessionGuildId } from '@/lib/tenant'
import { getMyAllianceContentRegearVideoContext } from '@/lib/alliance-content-regear-data'
import { getTenantTimezone } from '@/lib/timezone-server'
import { getRegearSupportConfiguration } from '@/lib/regear-support-server'

export const dynamic = 'force-dynamic'

export default async function MyRegearDetailPage({
  params,
}: {
  params: Promise<{ id: string }>
}) {
  const { id } = await params
  const session = await getSession()
  if (!session) {
    redirect(`/login?returnTo=${encodeURIComponent(`/me/regear/${id}`)}`)
  }
  if (!session.isMember) redirect('/')

  const { detail, error } = await getMyRegearDetail(id)
  if (error || !detail) notFound()

  const guildId = await getSessionGuildId(session)
  const [t, tRegear, allianceContentContext, timezone, regearSupport] = await Promise.all([
    getTranslations('common'),
    getTranslations('regear'),
    getMyAllianceContentRegearVideoContext(guildId, session.discordId, id),
    getTenantTimezone(guildId),
    getRegearSupportConfiguration(guildId),
  ])

  return (
    <main className="flex-1 w-full max-w-3xl mx-auto px-4 py-6 sm:py-8 space-y-4">
      <Link
        href="/me"
        className="inline-flex items-center gap-1 text-sm text-gray-400 hover:text-gray-200"
      >
        <ArrowLeft size={14} />
        {t('backToMyPage')}
      </Link>
      {!regearSupport.supported && (
        <section className="rounded-lg border border-sky-500/30 bg-sky-500/10 px-3 py-2">
          <p className="text-xs leading-relaxed text-sky-100/80">
            {tRegear('supportDisabledDescription')}
          </p>
        </section>
      )}
      {detail.autoGenerated ? (
        <MyRegearBreakdownEditor
          detail={detail}
          readOnly={!regearSupport.supported}
        />
      ) : (
        <MyManualRegearEditor
          detail={detail}
          allianceContentContext={allianceContentContext}
          timezone={timezone}
          readOnly={!regearSupport.supported}
        />
      )}
    </main>
  )
}
