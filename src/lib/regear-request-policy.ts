import type { RegearType } from '@/types'

export const MANUAL_REGEAR_MAX_BATCH_ENTRIES = 3

export type ManualRegearPhase = 'type' | 'count' | 'entries'
export type RegearLimitStatus = 'pending' | 'approved' | 'rejected'

export function getRemainingDeathClaims(
  activeDeathCount: number,
  maxDeaths: number,
): number {
  return Math.max(0, maxDeaths - activeDeathCount)
}

export function isDeathLimitReached(
  activeDeathCount: number,
  maxDeaths: number,
): boolean {
  return getRemainingDeathClaims(activeDeathCount, maxDeaths) <= 0
}

export function getDeathBatchEntryLimit(
  activeDeathCount: number,
  maxDeaths: number,
): number {
  return Math.max(
    1,
    Math.min(MANUAL_REGEAR_MAX_BATCH_ENTRIES, getRemainingDeathClaims(activeDeathCount, maxDeaths)),
  )
}

export function getEntryLimitForRequestType(
  requestType: RegearType,
  activeDeathCount: number,
  maxDeaths: number,
): number {
  if (requestType === 'overcharge') return 1
  return getDeathBatchEntryLimit(activeDeathCount, maxDeaths)
}

export function getInitialManualRegearPhase(
  overchargeEnabled: boolean,
  deathEntryLimit: number,
): ManualRegearPhase {
  if (overchargeEnabled) return 'type'
  return deathEntryLimit > 1 ? 'count' : 'entries'
}

export function canOpenManualRegearRequest(input: {
  baseEnabled: boolean
  activeDeathCount: number
  maxDeaths: number
  overchargeEnabled: boolean
}): boolean {
  if (!input.baseEnabled) return false
  return !isDeathLimitReached(input.activeDeathCount, input.maxDeaths) || input.overchargeEnabled
}

export function shouldListManualRegearEligibleEvent(input: {
  activeDeathCount: number
}): boolean {
  return input.activeDeathCount <= 0
}

export function countsTowardDeathLimit(input: {
  requestType: RegearType
  autoGenerated: boolean
  status: RegearLimitStatus
}): boolean {
  if (input.requestType !== 'death') return false
  if (input.status === 'rejected') return false
  // Pending auto-regear rows are only a draft source. The manual death submit
  // path supersedes them before enforcing the limit, so the member-facing
  // remaining count must not treat them as already consuming a death slot.
  if (input.autoGenerated && input.status === 'pending') return false
  return true
}
