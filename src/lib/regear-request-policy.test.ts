import { describe, expect, it } from 'vitest'
import {
  canAddManualRegearEntry,
  canOpenManualRegearRequest,
  countsTowardDeathLimit,
  getDeathBatchEntryLimit,
  getEntryLimitForRequestType,
  getInitialManualRegearPhase,
  getManualRegearEntryTypeCounts,
  getRemainingDeathClaims,
  isDeathLimitReached,
  shouldListManualRegearEligibleEvent,
} from './regear-request-policy'

describe('manual regear request policy', () => {
  it('counts only death claims against the death limit', () => {
    expect(getRemainingDeathClaims(2, 3)).toBe(1)
    expect(isDeathLimitReached(3, 3)).toBe(true)
    expect(getEntryLimitForRequestType('overcharge', 3, 3)).toBe(1)
  })

  it('does not count pending auto death rows that manual death submission can replace', () => {
    expect(
      countsTowardDeathLimit({
        requestType: 'death',
        autoGenerated: true,
        status: 'pending',
      }),
    ).toBe(false)
    expect(
      countsTowardDeathLimit({
        requestType: 'death',
        autoGenerated: true,
        status: 'approved',
      }),
    ).toBe(true)
    expect(
      countsTowardDeathLimit({
        requestType: 'overcharge',
        autoGenerated: false,
        status: 'pending',
      }),
    ).toBe(false)
  })

  it('allows opening the request flow at the death limit when overcharge is enabled', () => {
    expect(
      canOpenManualRegearRequest({
        baseEnabled: true,
        activeDeathCount: 3,
        maxDeaths: 3,
        overchargeEnabled: true,
      }),
    ).toBe(true)
  })

  it('blocks the request flow at the death limit when overcharge is disabled', () => {
    expect(
      canOpenManualRegearRequest({
        baseEnabled: true,
        activeDeathCount: 3,
        maxDeaths: 3,
        overchargeEnabled: false,
      }),
    ).toBe(false)
  })

  it('caps death batch choices by remaining deaths and the product batch max', () => {
    expect(getDeathBatchEntryLimit(0, 5)).toBe(3)
    expect(getDeathBatchEntryLimit(2, 3)).toBe(1)
  })

  it('keeps event and free manual regear flows on the same initial phase policy', () => {
    expect(getInitialManualRegearPhase(true, 1)).toBe('type')
    expect(getInitialManualRegearPhase(false, 1)).toBe('entries')
    expect(getInitialManualRegearPhase(false, 2)).toBe('count')
  })

  it('removes an event from the manual eligible list after any active death request', () => {
    expect(shouldListManualRegearEligibleEvent({ activeDeathCount: 0 })).toBe(true)
    expect(shouldListManualRegearEligibleEvent({ activeDeathCount: 1 })).toBe(false)
    expect(shouldListManualRegearEligibleEvent({ activeDeathCount: 2 })).toBe(false)
  })

  it('allows one death and one overcharge in the same manual batch', () => {
    const entries = [{ requestType: 'death' as const }]

    expect(getManualRegearEntryTypeCounts(entries)).toEqual({
      death: 1,
      overcharge: 0,
    })
    expect(
      canAddManualRegearEntry({
        entries,
        requestType: 'overcharge',
        activeDeathCount: 0,
        maxDeaths: 1,
        overchargeEnabled: true,
      }),
    ).toBe(true)
  })

  it('enforces death limits separately from the optional overcharge entry', () => {
    const entries = [
      { requestType: 'death' as const },
      { requestType: 'overcharge' as const },
    ]

    expect(getManualRegearEntryTypeCounts(entries)).toEqual({
      death: 1,
      overcharge: 1,
    })
    expect(
      canAddManualRegearEntry({
        entries,
        requestType: 'death',
        activeDeathCount: 0,
        maxDeaths: 1,
        overchargeEnabled: true,
      }),
    ).toBe(false)
    expect(
      canAddManualRegearEntry({
        entries,
        requestType: 'overcharge',
        activeDeathCount: 0,
        maxDeaths: 1,
        overchargeEnabled: true,
      }),
    ).toBe(false)
  })
})
